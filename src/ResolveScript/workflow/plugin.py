_BRIDGE_JS = """\
// Generated by ResolveScript. One JSON object per line, in both directions.
// The contract is documented in ResolveScript.workflow.bridge and the Python
// half ships with ResolveScript, so both ends change together.
'use strict';

const { spawn } = require('child_process');

class Bridge {
    constructor({ python, script, name }) {
        this.python = python;
        this.script = script;
        this.name = name;
        this.child = null;
        this.buffer = '';
        this.pending = new Map();
    }

    async start() {
        return new Promise((resolve) => {
            let child;
            try {
                child = spawn(this.python, [this.script, '--serve'], {
                    stdio: ['pipe', 'pipe', 'pipe'],
                    windowsHide: true
                });
            } catch (err) {
                resolve({ ok: false, error: err.message });
                return;
            }
            this.child = child;

            child.stdout.setEncoding('utf8');
            child.stdout.on('data', (chunk) => this.consume(chunk));
            child.stderr.setEncoding('utf8');
            child.stderr.on('data', (chunk) =>
                console.error('[' + this.name + ']', String(chunk).trim())
            );
            child.on('error', (err) => this.fail(err));
            child.on('close', (code) => {
                for (const entry of this.pending.values()) {
                    clearTimeout(entry.timer);
                    entry.resolve({
                        ok: false,
                        error: 'the Python integration exited with code ' + code
                    });
                }
                this.pending.clear();
            });

            // The protocol has no handshake, so ping is how this side learns
            // the interpreter started and imported the integration.
            this.request({ action: 'ping' }).then(resolve);
        });
    }

    consume(chunk) {
        this.buffer += chunk;
        let index = this.buffer.indexOf('\\n');
        while (index !== -1) {
            const line = this.buffer.slice(0, index).trim();
            this.buffer = this.buffer.slice(index + 1);
            if (line) {
                this.dispatch(line);
            }
            index = this.buffer.indexOf('\\n');
        }
    }

    dispatch(line) {
        let message;
        try {
            message = JSON.parse(line);
        } catch (err) {
            console.error('Unparseable message from the integration:', line);
            return;
        }
        const entry = this.pending.get(message.id);
        if (entry === undefined) {
            return;
        }
        this.pending.delete(message.id);
        clearTimeout(entry.timer);
        entry.resolve(message);
    }

    fail(err) {
        for (const entry of this.pending.values()) {
            clearTimeout(entry.timer);
            entry.resolve({ ok: false, error: err.message });
        }
        this.pending.clear();
    }

    request(payload, timeoutMs = 30000) {
        if (this.child === null || this.child.killed) {
            return Promise.resolve({
                ok: false,
                error: 'the Python integration is not running'
            });
        }
        // Replies come back in request order, so they do not need an id echoed
        // from the Python side. The queue below pairs them anyway, which keeps
        // a slow or crashing child from shifting every later reply by one.
        const id = this.pending.size;
        return new Promise((resolve) => {
            const timer = setTimeout(() => {
                this.pending.delete(id);
                resolve({ ok: false, error: 'the integration did not respond' });
            }, timeoutMs);
            this.pending.set(id, { resolve, timer });
            try {
                this.child.stdin.write(JSON.stringify(payload) + '\\n');
            } catch (err) {
                this.pending.delete(id);
                clearTimeout(timer);
                resolve({ ok: false, error: err.message });
            }
        });
    }

    close() {
        if (this.child !== null && !this.child.killed) {
            try {
                this.child.stdin.write(JSON.stringify({ action: 'quit' }) + '\\n');
            } catch (err) {
                // The child is already gone; killing it below is enough.
            }
            this.child.kill();
        }
        this.child = null;
    }
}

module.exports = { Bridge };
"""

