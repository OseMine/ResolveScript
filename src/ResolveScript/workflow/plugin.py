"""Generating the Electron Workflow Integration plugin.

A plugin is an Electron app that Resolve launches as its main process, and it
only works on Windows and macOS. Resolve reads ``manifest.xml`` at scan time to
build the menu entry, and hands the app a native Node addon,
``WorkflowIntegration.node``, which is the only way to reach Resolve's
JavaScript API — and the only way Resolve delivers callbacks.

So the two artifacts are not alternatives. The plugin is a shell: it owns the
window, owns the callbacks, and talks to the Python integration that this
project actually ships. :func:`render_plugin` writes the shell; see
:mod:`ResolveScript.workflow.script` for the brain.

The file layout matches what Resolve documents and what the shipped plugins
use::

    com.acme.deliver/
        manifest.xml        <BlackmagicDesign><Plugin> — Id, Name, Version,
                             Description, FilePath. Read at scan time.
        package.json        standard Electron app manifest, "main": "main.js"
        main.js             Electron main process: loads the native addon,
                             registers callbacks, runs the Python bridge
        preload.js          contextBridge surface for the renderer
        index.html          the page Resolve shows
        js/bridge.js        line-protocol client for the Python process
        js/app.js           the page's behaviour
        css/app.css

Substitution is done with ``@@TOKEN@@`` replacement rather than
``str.format``: these templates are JavaScript and CSS, so nearly every line
braces, and escaping them all would be one forgotten brace away from shipping
broken code. :func:`_fill` is the only place a template is interpolated.

Token names carry their context — ``@@JS_ID@@`` is JSON-encoded, ``@@XML_ID@@``
is XML-escaped, ``@@HTML_ID@@`` is HTML-escaped — because the same value is
needed in three encodings, and one shared ``@@ID@@`` would put JSON quotes
inside an HTML ``<title>``.
"""

