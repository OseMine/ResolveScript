_APP_JS = """\
// Generated by ResolveScript. The page reads the integration's metadata from
// the Python process rather than duplicating it, so the two can never disagree
// about which callbacks exist.
'use strict';

const $ = (id) => document.getElementById(id);
const status = $('status');

function setStatus(text, isError) {
    status.textContent = text;
    status.classList.toggle('status--error', Boolean(isError));
}

function show(node, value) {
    node.textContent =
        value === null || value === undefined || value === '' ? '—' : String(value);
}

async function describe() {
    const reply = await window.workflow.describe();
    if (!reply.ok) {
        setStatus(reply.error, true);
        return null;
    }
    const meta = reply.result;
    document.title = meta.name;
    show(document.querySelector('.panel__title'), meta.name);
    document.querySelector('.panel__version').textContent =
        meta.version + ' · ' + meta.id;

    const section = $('callbacks');
    if (meta.callbacks.length === 0) {
        section.hidden = true;
        return meta;
    }
    section.hidden = false;
    const actions = $('callback-actions');
    actions.replaceChildren();
    for (const name of meta.callbacks) {
        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'button';
        button.textContent = name;
        button.addEventListener('click', () => runCallback(name, button));
        actions.append(button);
    }
    return meta;
}

async function refresh() {
    const reply = await window.workflow.context();
    if (!reply.ok) {
        setStatus(reply.error, true);
        return;
    }
    const info = reply.result;
    show($('fact-project'), info.project);
    show($('fact-timeline'), info.timeline);
    show($('fact-jobs'), info.render_jobs);
    setStatus(info.connected ? 'Connected' : 'Not connected to Resolve', !info.connected);
}

async function runCallback(name, button) {
    button.disabled = true;
    const log = $('callback-log');
    log.hidden = false;
    const reply = await window.workflow.callback(name);
    log.textContent = name + ' -> ' + (reply.ok ? JSON.stringify(reply.result) : reply.error);
    button.disabled = false;
}

$('refresh').addEventListener('click', refresh);

(async function start() {
    if (!window.workflow) {
        setStatus('preload failed - no bridge', true);
        return;
    }
    const ping = await window.workflow.ping();
    if (!ping.ok) {
        setStatus(ping.error, true);
        return;
    }
    await describe();
    await refresh();
})();
"""

