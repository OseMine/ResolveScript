def render_plugin(
    integration: Integration,
    *,
    script_rel: str = "",
    width: int = 420,
    height: int = 620,
    search_paths: list[str] | None = None,
) -> dict[str, str]:
    """Return the plugin's files as ``{relative path: source}``.

    Pure — nothing is written; :mod:`ResolveScript.workflow.build` does that.

    :param script_rel: where the generated Python launcher sits, relative to
        the plugin directory. Defaults to the launcher in the parent, which is
        where :func:`~ResolveScript.workflow.build.build` puts it.
    :param width: the window's width in pixels.
    :param height: the window's height in pixels.
    :param search_paths: full paths to look for ``WorkflowIntegration.node`` in;
        defaults to the copies inside Resolve's bundled sample plugins.
    """
    if search_paths is None:
        search_paths = [str(path) for path in native_module_source()]

    description = integration.description or integration.name
    slug = integration.id.replace(".", "-")
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
        # npm rejects these, and a plugin whose package.json is not installable
        # fails long after Resolve has already found it.
        raise PluginRenderError(
            f"integration id {integration.id!r} does not produce a usable npm "
            f"package name ({slug!r}); use lowercase letters, digits and dots"
        )

    tokens = {
        # JSON encoding — for values interpolated into JavaScript source and
        # into package.json, where they must be valid JSON values.
        "JSON_ID": json.dumps(integration.id),
        "JSON_NAME": json.dumps(integration.name),
        "JSON_VERSION": json.dumps(integration.version),
        "JSON_DESCRIPTION": json.dumps(description),
        "JSON_AUTHOR": json.dumps(integration.author or "ResolveScript"),
        "JSON_LICENSE": json.dumps(integration.license),
        "JSON_ELECTRON": json.dumps(ELECTRON_VERSION),
        "JSON_CALLBACKS": json.dumps(sorted(integration.callbacks)),
        "JSON_PYTHON": json.dumps(integration.python),
        "JSON_SCRIPT": json.dumps(script_rel or f"../{integration.script_name}"),
        "JSON_SEARCH_PATHS": json.dumps(search_paths),
        # Bare JavaScript — numbers and already-quoted strings.
        "JS_ID": json.dumps(integration.id),
        "JS_NAME": json.dumps(integration.name),
        "JS_API_TIMEOUT": str(int(integration.api_timeout)),
        "JS_WIDTH": str(int(width)),
        "JS_HEIGHT": str(int(height)),
        # Markup escaping — text content, so no surrounding quotes.
        "XML_ID": xml_escape(integration.id),
        "XML_NAME": xml_escape(integration.name),
        "XML_VERSION": xml_escape(integration.version),
        "XML_DESCRIPTION": xml_escape(description),
        "HTML_NAME": html_escape(integration.name),
        "HTML_VERSION": html_escape(integration.version),
        "HTML_ID": html_escape(integration.id),
        "SLUG": slug,
    }

    files = {
        "manifest.xml": _fill(_MANIFEST, tokens),
        "package.json": _fill(_PACKAGE, tokens),
        "main.js": _fill(_MAIN_JS, tokens),
        "preload.js": _PRELOAD_JS,
        "index.html": _fill(_INDEX_HTML, tokens),
        "js/bridge.js": _BRIDGE_JS,
        "js/app.js": _APP_JS,
        "css/app.css": _APP_CSS,
    }
    _verify(files)
    return files


def _verify(files: dict[str, str]) -> None:
    """Fail loudly on the two files a mistake in them would hide.

    A package.json that is not valid JSON still installs — npm is never run by
    Resolve — so the only signal is the plugin failing to launch much later,
    with nothing pointing at the cause. Checking it here costs nothing.
    """
    try:
        json.loads(files["package.json"])
    except ValueError as exc:
        raise PluginRenderError(f"generated package.json is not valid JSON: {exc}") from exc
    try:
        ElementTree.fromstring(files["manifest.xml"])
    except ElementTree.ParseError as exc:
        raise PluginRenderError(f"generated manifest.xml is not valid XML: {exc}") from exc
