def _as_node(source: Any) -> Node:
    if isinstance(source, Node):
        return source
    if isinstance(source, Component):
        return source.to_node()
    if isinstance(source, Raw):
        raise SchemaError("a Raw node carries a callable and cannot be serialised; "
                          "describe it as {'kind': 'raw', 'type': 'TextEdit'} instead")
    if isinstance(source, Mapping):
        return from_dict(source)
    raise SchemaError(f"expected a Node, got {type(source).__name__}")


def _component_or_error(kind: str) -> type[Component]:
    try:
        return get_component(kind)
    except Exception as exc:
        widgets = sorted(all_specs())
        raise SchemaError(
            f"{kind!r} is neither a widget nor a registered component. "
            f"Widgets: {widgets}"
        ) from exc


def _encode_props(
    props: Mapping[str, Any],
    *,
    spec: Any,
    values: bool,
    skip: set[str],
) -> dict[str, Any]:
    """Serialise props, omitting anything left at its default.

    Dropping defaults keeps an exported template readable: a button that is
    merely a button serialises as ``{"text": "Go"}``, not as a page of
    ``false``/``0``/``""`` that restates the spec.
    """
    from .state import is_reactive

    out: dict[str, Any] = {}
    for name, value in props.items():
        if name in skip or name == "theme":
            continue
        if name.startswith("on_") and callable(value):
            continue
        if callable(value) or isinstance(value, Component):
            continue

        source = value.source if isinstance(value, TwoWay) else value
        # ``values=False`` keeps the live object, so a document re-attaches to
        # the same state instead of a snapshot taken at export time.
        live = is_reactive(source)
        if live and values:
            value = source.get()
        elif not live and spec is not None and _is_default(spec.props.get(name), value):
            continue

        out[name] = value if (live and not values) else _plain(value)
    return out


def _is_default(prop: Any, value: Any) -> bool:
    from .spec import UNSET

    if prop is None or prop.default is UNSET:
        return False
    if value is prop.default:
        return True
    try:
        return bool(value == prop.default)
    except Exception:  # pragma: no cover - exotic __eq__
        return False


def _plain(value: Any) -> Any:
    """Coerce a prop into something ``json.dumps`` accepts."""
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, TwoWay):
        return _plain(value.source)
    from .state import is_reactive

    if is_reactive(value):
        return _plain(value.get())
    if isinstance(value, Mapping):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_plain(item) for item in value]
    if hasattr(value, "to_dict"):
        return value.to_dict()
    if hasattr(value, "hex"):  # Color
        return str(value.hex)
    return str(value)


def _json_default(value: Any) -> Any:
    if isinstance(value, Node):
        return to_dict(value)
    return _plain(value)
